// Builds the single-file asset preparation tool for players:
//
//   node native/tools/asset-prep/build.mjs        ->  native/tools/asset-prep/dist/prepare-assets.mjs
//
// The output runs with plain `node prepare-assets.mjs --game <dir> --out <dir>` from any folder, with no
// node_modules and no checkout: esbuild (already in node_modules; nothing is downloaded) bundles prepare.ts,
// every stage script it runs, all the TypeScript they import, pngjs and anything else they pull in; only
// node: builtins stay external. Two things are frozen in at build time because the bundle has no checkout:
//   - embedded.ts is replaced by its data (embedded-sources.mjs): the identity constants parsed from the C++
//     headers and the three game/src/core/data files the stages read, as exact bytes;
//   - import.meta.url, which the stage scripts use only to find checkout-relative DEFAULT paths, is replaced
//     by a URL inside <os temp>/ultima-v-asset-prep-no-checkout, a folder nothing creates. The orchestrator
//     always passes explicit paths, and it fails the run if that folder ever appears (a stage that fell back
//     to a default). It also keeps audio.ts's "am I the main module?" check false inside the bundle.
// The bundle holds no Ultima V game data; it reads the player's own files at run time.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { collectEmbedded } from "./embedded-sources.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../../..");
const outfile = join(here, "dist", "prepare-assets.mjs");
const require = createRequire(import.meta.url);
const esbuild = require("esbuild");

// Provenance printed by the tool: the commit, plus "+dirty" when anything the bundle is built from differs
// from it (the tool scripts, the extractor, the game sources the stages import, the identity headers).
let commit = "unknown";
try {
  commit = execFileSync("git", ["-C", repoRoot, "rev-parse", "--short=12", "HEAD"], { encoding: "utf8" }).trim();
  const changed = execFileSync("git", ["-C", repoRoot, "--no-optional-locks", "status", "--porcelain", "--",
    "native/tools", "extractor",
    "game/src", "native/core/tools", "native/targets/tdeck/main/asset_pack.h",
    "native/targets/tdeck/main/alpha_resources.h"], { encoding: "utf8" }).trim();
  if (changed) commit += "+dirty";
} catch { /* not a git checkout: keep "unknown" */ }

const embedded = { origin: "bundle", commit, ...collectEmbedded(repoRoot) };

/** Swaps ./embedded.js (imported by prepare.ts) for the frozen data. */
const embeddedPlugin = {
  name: "asset-prep-embedded",
  setup(build) {
    build.onResolve({ filter: /^\.\/embedded\.js$/ }, (args) =>
      resolve(args.resolveDir) === here ? { path: "embedded", namespace: "asset-prep" } : undefined);
    build.onLoad({ filter: /.*/, namespace: "asset-prep" }, () => ({
      contents: `export const EMBEDDED = ${JSON.stringify(embedded)};\n`,
      loader: "js",
    }));
  },
};

/**
 * Two tracked JSON files that the reference port's modules import statically but that no pack depends on
 * are replaced by empty stand-ins, so no game text ships with the tool:
 *   - game/src/i18n/es.json, the Spanish translation table: the engine runs in English, where i18n's t() is
 *     the identity and never reads it;
 *   - game/src/core/data/longEquipNames.json, the equipment names dumped from DATA.OVL: used only for shop
 *     and search messages, never for the combat tables the fixture stage derives.
 * The identity check on the packs proves neither changes a byte of the output.
 */
const STUBS = [
  { file: /[\\/]i18n[\\/]es\.json$/, contents: { meta: { lang: "es", name: "Espanol", seed: true }, strings: {} } },
  { file: /[\\/]core[\\/]data[\\/]longEquipNames\.json$/, contents: { names: [] } },
];
const stubsPlugin = {
  name: "asset-prep-stubs",
  setup(build) {
    build.onLoad({ filter: /\.json$/ }, (args) => {
      const stub = STUBS.find((s) => s.file.test(args.path));
      return stub ? { contents: JSON.stringify(stub.contents), loader: "json" } : undefined;
    });
  },
};

const banner = [
  "// Ultima V Native - resource pack preparation: single-file build of native/tools/asset-prep/prepare.ts",
  `// (commit ${commit}), generated by native/tools/asset-prep/build.mjs -- do not edit.`,
  "// Usage: node prepare-assets.mjs --game <Ultima V folder> --out <folder>   (--help for options)",
  "// Contains no Ultima V game data: it reads the player's own copy of the game at run time.",
  "// Ultima V Native is GPL-3.0. Bundled third-party code and data: pngjs (MIT); game/src/core/data JSON",
  "// (tile, enemy and shop metadata) from Ultima5Redux by Brad Hannah (MIT,",
  "// https://github.com/bradhannah/Ultima5Redux). No translation tables and no game text are included.",
  'import { createRequire as __assetPrepCreateRequire } from "node:module";',
  'import { tmpdir as __assetPrepTmpdir } from "node:os";',
  'import { join as __assetPrepJoin } from "node:path";',
  'import { pathToFileURL as __assetPrepPathToFileURL } from "node:url";',
  "const require = __assetPrepCreateRequire(import.meta.url);",
  "const __assetPrepModuleUrl = __assetPrepPathToFileURL(__assetPrepJoin(__assetPrepTmpdir(),",
  '  "ultima-v-asset-prep-no-checkout", "native", "tools", "asset-prep", "prepare-assets.mjs")).href;',
].join("\n");

mkdirSync(dirname(outfile), { recursive: true });
const result = await esbuild.build({
  entryPoints: [join(here, "prepare.ts")],
  outfile,
  // The module path comments esbuild writes are relative to the working directory: pin it, and keep the
  // node_modules path as seen from the checkout (it may be a junction), so the output does not depend on
  // where the build was started from.
  absWorkingDir: repoRoot,
  preserveSymlinks: true,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node18",
  define: { "import.meta.url": "__assetPrepModuleUrl" },
  banner: { js: banner },
  plugins: [embeddedPlugin, stubsPlugin],
  legalComments: "eof",
  metafile: true,
  logLevel: "warning",
});

const bytes = readFileSync(outfile);
// The stubs must have taken: each stubbed file entered the bundle as its few-byte stand-in (esbuild's
// metafile records the size it loaded), and a line unique to the Spanish table is absent.
for (const [path, input] of Object.entries(result.metafile.inputs)) {
  if (STUBS.some((s) => s.file.test(path.replace(/\//g, "\\"))) && input.bytes > 200) {
    console.error(`refusing the bundle: ${path} entered with ${input.bytes} bytes, not its stand-in`);
    process.exit(1);
  }
}
if (bytes.includes(Buffer.from("Se llama Emilly"))) {
  console.error("refusing the bundle: it still contains the Spanish translation table");
  process.exit(1);
}
const inputs = Object.keys(result.metafile.inputs);
const packages = [...new Set(inputs.map((p) => /node_modules[\\/]((?:@[^\\/]+[\\/])?[^\\/]+)/.exec(p)?.[1])
  .filter(Boolean))].sort();
// Data the bundle may carry: an explicit list, so the next unintended import of game data breaks the
// build instead of shipping. Nothing may come from the player's game folders or the packs.
const ALLOWED_JSON = ["game/src/core/data/TileData.json"]; // Ultima5Redux tile metadata (MIT)
const dataInputs = [];
for (const path of inputs) {
  const p = path.replace(/\\/g, "/");
  if (/(^|\/)(original|game\/assets|native\/assets)\//.test(p)) {
    console.error(`refusing the bundle: it would carry ${p}`);
    process.exit(1);
  }
  if (!p.endsWith(".json") || STUBS.some((s) => s.file.test(path))) continue;
  if (!ALLOWED_JSON.includes(p)) {
    console.error(`refusing the bundle: ${p} is not on the JSON allowlist in build.mjs`);
    process.exit(1);
  }
  dataInputs.push(p);
}

// The manifest the Windows packaging reads: provenance, the hash, and what to credit.
const sha256 = createHash("sha256").update(bytes).digest("hex");
writeFileSync(join(here, "dist", "prepare-assets.manifest.json"), JSON.stringify({
  file: "prepare-assets.mjs", bytes: bytes.length, sha256, commit,
  packages, dataInputs, embeddedData: embedded.data ? Object.keys(embedded.data).sort() : [],
}, null, 2) + "\n");
console.log(`Wrote ${relative(process.cwd(), outfile) || outfile}`);
console.log(`  ${bytes.length.toLocaleString("en-US")} bytes, SHA-256 ${sha256}`);
console.log(`  ${inputs.length} modules bundled; packages: ${packages.join(", ") || "none"}; commit ${commit}`);
console.log(`  identity: ${Object.entries(embedded.identity).map(([n, i]) => `${n} ${i.size} B CRC ${i.crc32}`).join("; ")}`);
console.log(`  data: ${[...dataInputs, ...Object.keys(embedded.data).map((n) => `${n} (embedded)`)].join(", ")}`);
